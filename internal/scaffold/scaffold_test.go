// The point of generating a repository is that it reconciles as it stands, so the
// test that matters is discovery reading what was written.
func TestGeneratedRepositoryIsDiscovered(t *testing.T) {
	dir := t.TempDir()
	if _, err := Write(dir, Files("example", false)); err != nil {
		t.Fatal(err)
	}

	result, err := discover.Walk(dir)
	if err != nil {
		t.Fatalf("discovery failed on a generated repository: %v", err)
	}
	if result.Set.Fleet.Name != "example" {
		t.Errorf("fleet = %q, want example", result.Set.Fleet.Name)
	}
	if len(result.Set.Layers) != 1 || result.Set.Layers[0].Name != "base" {
		t.Errorf("layers = %+v, want one named base", result.Set.Layers)
	}
	if len(result.Set.Resources) != 0 {
		t.Errorf("resources = %+v, want none", result.Set.Resources)
	}
}

func TestExamplesAreDiscovered(t *testing.T) {
	dir := t.TempDir()
	written, err := Write(dir, Files("example", true))
	if err != nil {
		t.Fatal(err)
	}
	if len(written) != 4 {
		t.Fatalf("wrote %d files, want 4: %v", len(written), written)
	}

	result, err := discover.Walk(dir)
	if err != nil {
		t.Fatalf("discovery failed with examples: %v", err)
	}
	if len(result.Set.Hosts) != 1 || result.Set.Hosts[0].Name != "example-host" {
		t.Errorf("hosts = %+v, want one named example-host", result.Set.Hosts)
	}
	if len(result.Set.Resources) != 1 {
		t.Fatalf("resources = %+v, want one", result.Set.Resources)
	}
	// The example resource has to land in the layer beside it, since that is the
	// one rule the comment in the file claims.
	if got := result.Set.Resources[0].Layer; got != "base" {
		t.Errorf("layer = %q, want base", got)
	}
}

// Datum writes the version it understands, so a repository generated by an agent
// always matches that agent.
func TestGeneratedDocumentsDeclareTheCurrentSchema(t *testing.T) {
	for _, file := range Files("example", true) {
		if !strings.Contains(file.Body, "datum: "+document.SchemaVersion+"\n") {
			t.Errorf("%s does not declare %s:\n%s", file.Path, document.SchemaVersion, file.Body)
		}
	}
}

