func TestWriteRefusesToOverwrite(t *testing.T) {
	dir := t.TempDir()
	existing := filepath.Join(dir, "fleet", "base", "layer.yaml")
	if err := os.MkdirAll(filepath.Dir(existing), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(existing, []byte("mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if _, err := Write(dir, Files("example", false)); err == nil {
		t.Fatal("writing over an existing document should fail")
	}

	// Nothing at all should have been written, including the file that comes
	// before the clash.
	if body, err := os.ReadFile(existing); err != nil || string(body) != "mine\n" {
		t.Errorf("the existing file was modified: %q %v", body, err)
	}
	if _, err := os.Stat(filepath.Join(dir, "fleet", "datum.yaml")); !os.IsNotExist(err) {
		t.Errorf("fleet/datum.yaml was written despite the clash: %v", err)
	}
}

func TestWriteDoesNotLeavePartialDocumentsWhenAPathIsBlocked(t *testing.T) {
	dir := t.TempDir()
	blocked := filepath.Join(dir, "fleet", "base")
	if err := os.MkdirAll(filepath.Dir(blocked), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(blocked, []byte("not a directory\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if _, err := Write(dir, Files("example", false)); err == nil {
		t.Fatal("writing should fail when a destination directory is blocked")
	}

	if _, err := os.Stat(filepath.Join(dir, "fleet", "datum.yaml")); !os.IsNotExist(err) {
		t.Errorf("fleet/datum.yaml was written despite the blocked path: %v", err)
	}
}
